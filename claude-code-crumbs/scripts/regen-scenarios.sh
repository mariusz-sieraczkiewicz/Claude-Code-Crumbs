#!/usr/bin/env bash
set -euo pipefail

# regen-scenarios.sh
# Rebuild docs/planning/SCENARIOS.md from docs/planning/epics.yaml
# Usage: ./regen-scenarios.sh

EPICS_YAML="docs/planning/epics.yaml"
OUT_FILE="docs/planning/SCENARIOS.md"
TMP_FILE="${OUT_FILE}.tmp.$$"

# Atomic write discipline: write to SCENARIOS.md.tmp first, rename on success.
# On any error before the final rename, leave the tmp file in place and exit non-zero
# so the user can inspect what went wrong. The real SCENARIOS.md is never touched
# unless the tmp write fully succeeded.
cleanup_on_error() {
    # Keep the tmp file around for diagnostics; do NOT remove it.
    echo "Error: regen-scenarios.sh failed; leaving ${TMP_FILE} in place for inspection." >&2
}
trap cleanup_on_error ERR

# Nothing to do if epics.yaml is absent.
if [ ! -f "$EPICS_YAML" ]; then
    exit 0
fi

if ! command -v python3 >/dev/null 2>&1; then
    echo "Error: python3 is required. Install Python 3.8+ and then run:" >&2
    echo "  pip install pyyaml" >&2
    exit 2
fi

if ! python3 -c "import yaml" >/dev/null 2>&1; then
    echo "Error: missing Python lib pyyaml. Install with:" >&2
    echo "  pip install pyyaml" >&2
    exit 2
fi

mkdir -p "$(dirname "$OUT_FILE")"

python3 - "$EPICS_YAML" "$TMP_FILE" <<'PY'
import re
import sys
import yaml

epics_path, out_path = sys.argv[1], sys.argv[2]

with open(epics_path, "r", encoding="utf-8-sig") as f:
    data = yaml.safe_load(f) or {}

epics = data.get("epics") or []
if not isinstance(epics, list):
    epics = []

scenario_re = re.compile(r"^\s*##\s*Scenario:\s*(.+?)\s*$", re.MULTILINE)

lines = []
lines.append("# Business Scenarios — flat index")
lines.append("")
lines.append("<!-- Auto-generated by scripts/regen-scenarios.sh. Do not edit by hand. -->")
lines.append("")

total_scenarios = 0
epics_with_scenarios = 0

if not epics:
    lines.append("*(no scenarios yet)*")
    lines.append("")
else:
    body_parts = []
    for epic in epics:
        if not isinstance(epic, dict):
            continue
        epic_id = epic.get("id") or "(unknown)"
        title = epic.get("title") or ""
        block = epic.get("business_scenarios") or ""
        if not isinstance(block, str):
            block = ""
        names = scenario_re.findall(block)
        if not names:
            continue
        epics_with_scenarios += 1
        total_scenarios += len(names)
        body_parts.append(f"## Epic {epic_id}: {title}")
        body_parts.append("")
        for n in names:
            body_parts.append(f"- Scenario: {n}")
        body_parts.append("")
    if not body_parts:
        lines.append("*(no scenarios yet)*")
        lines.append("")
    else:
        lines.extend(body_parts)

with open(out_path, "w", encoding="utf-8") as f:
    f.write("\n".join(lines).rstrip() + "\n")
# Note: output stays plain utf-8 (no BOM); input reader uses utf-8-sig to strip BOM.

print(f"{total_scenarios} {epics_with_scenarios}")
PY

# Atomic rename: only after the tmp file is fully written and the python block
# exited 0 do we promote it to the canonical path. POSIX rename(2) is atomic on
# the same filesystem.
if ! mv "$TMP_FILE" "$OUT_FILE"; then
    echo "Error: failed to rename ${TMP_FILE} to ${OUT_FILE}. Tmp file preserved for inspection." >&2
    exit 4
fi

# Capture counts from the python output by re-running a lightweight parse.
read -r N M < <(python3 - "$EPICS_YAML" <<'PY'
import re, sys, yaml
with open(sys.argv[1], "r", encoding="utf-8-sig") as f:
    data = yaml.safe_load(f) or {}
epics = data.get("epics") or []
sre = re.compile(r"^\s*##\s*Scenario:\s*(.+?)\s*$", re.MULTILINE)
total = 0
mcount = 0
for e in epics if isinstance(epics, list) else []:
    if not isinstance(e, dict):
        continue
    block = e.get("business_scenarios") or ""
    if not isinstance(block, str):
        block = ""
    names = sre.findall(block)
    if names:
        mcount += 1
        total += len(names)
print(f"{total} {mcount}")
PY
)

echo "Regenerated ${OUT_FILE} (${N} scenarios across ${M} epics)"
